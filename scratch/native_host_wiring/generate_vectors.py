#!/usr/bin/env python3
"""Generate canonical native display vectors from the Python contracts.

Pure offline generator. It writes the JSON vectors and a C++ table fragment
that is pasted verbatim into prototype/classic/main.cpp, so the compiled
self-test and the Python producer share one expected set. No Qt, no hardware,
no service and no runtime claim.
"""
from __future__ import annotations

import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from canopy_features.quick_controls.native_display_contract import (  # noqa: E402
    NativeDisplayProducer,
)

HERE = Path(__file__).resolve().parent


def recovery(connectors, primary, width=1920, height=1080):
    return {"call": "recovery", "connectors": list(connectors),
            "primary": primary, "width": width, "height": height}


def dpi(width, height, scale, connector="HDMI-1"):
    return {"call": "dpi", "width": width, "height": height,
            "scale": scale, "connector": connector}


CASES = [
    ("recovery_initial", [recovery(["HDMI-1"], "HDMI-1")]),
    ("recovery_secondary_connect", [
        recovery(["HDMI-1"], "HDMI-1"),
        recovery(["HDMI-1", "DP-1"], "HDMI-1")]),
    ("recovery_resolution_changed", [
        recovery(["HDMI-1"], "HDMI-1"),
        recovery(["HDMI-1"], "HDMI-1", 1280, 720)]),
    ("recovery_primary_changed", [
        recovery(["HDMI-1", "DP-1"], "HDMI-1"),
        recovery(["HDMI-1", "DP-1"], "DP-1")]),
    ("recovery_unsupported_clamped", [
        recovery(["HDMI-1"], "HDMI-1", 1600, 1000)]),
    ("recovery_last_monitor_removed", [
        recovery(["HDMI-1"], "HDMI-1"),
        {"call": "recovery", "connectors": [], "primary": None,
         "width": None, "height": None}]),
    ("dpi_150_percent", [dpi(1920, 1080, 1.5)]),
    ("dpi_200_percent", [dpi(1920, 1080, 2.0)]),
    ("dpi_logical_unchanged", [dpi(1200, 750, 1.0)]),
    ("dpi_below_minimum", [dpi(1000, 600, 2.0)]),
    ("dpi_duplicate_signal", [dpi(1920, 1080, 1.5), dpi(1920, 1080, 1.5)]),
    ("dpi_hostile_scale", [dpi(1920, 1080, 5.0)]),
    ("dpi_hostile_connector", [dpi(1920, 1080, 1.5, "bad|connector")]),
]


def evaluate(steps):
    producer = NativeDisplayProducer()
    plan = None
    for step in steps:
        if step["call"] == "recovery":
            plan = producer.apply_recovery({
                "connectors": step["connectors"],
                "primary": step["primary"],
                "width": step["width"],
                "height": step["height"],
                "source": "qt.screen",
            })
        else:
            plan = producer.apply_logical_dpi(
                step["width"], step["height"], step["scale"],
                connector=step["connector"], source="qt.screen")
    return plan


def cpp_string(value):
    return json.dumps(value, ensure_ascii=True)


def main():
    vectors = []
    for name, steps in CASES:
        plan = evaluate(steps)
        vectors.append({"id": name, "steps": steps, "expected": plan})

    (HERE / "canonical_vectors.json").write_text(
        json.dumps({"wire_version": 1, "cases": vectors},
                   indent=2, sort_keys=True) + "\n", encoding="utf-8",
        newline="\n")

    flat_steps = []
    case_rows = []
    for case in vectors:
        start = len(flat_steps)
        for step in case["steps"]:
            connectors = step.get("connectors") or []
            flat_steps.append(
                "    {%s, %s, %s, %d, %d, %.3f, %s}," % (
                    cpp_string(step["call"]),
                    cpp_string(",".join(connectors)),
                    cpp_string(step.get("primary") or ""),
                    step.get("width") or 0,
                    step.get("height") or 0,
                    step.get("scale") or 1.0,
                    cpp_string(step.get("connector") or "")))
        expected = case["expected"]
        case_rows.append(
            "    {%s, %d, %d, %s, %s, %d, %d}," % (
                cpp_string(case["id"]), start, len(case["steps"]),
                cpp_string(expected["kind"]),
                cpp_string(expected["reason"]),
                expected["width"], expected["height"]))

    fragment = "\n".join([
        "// Generated by scratch/native_host_wiring/generate_vectors.py.",
        "struct NativeDisplayFixtureStep {",
        "    const char *call; const char *connectors; const char *primary;",
        "    int width; int height; double scale; const char *connector;",
        "};",
        "struct NativeDisplayFixtureCase {",
        "    const char *id; int start; int count;",
        "    const char *kind; const char *reason; int width; int height;",
        "};",
        "static const NativeDisplayFixtureStep kNativeDisplaySteps[] = {",
        *flat_steps,
        "};",
        "static const NativeDisplayFixtureCase kNativeDisplayCases[] = {",
        *case_rows,
        "};",
        "",
    ])
    (HERE / "canonical_vectors_cpp.txt").write_text(
        fragment, encoding="utf-8", newline="\n")
    print("generated %d cases / %d steps" % (len(vectors), len(flat_steps)))
    for case in vectors:
        expected = case["expected"]
        print("%-30s %-8s %4dx%-4d %s" % (
            case["id"], expected["kind"], expected["width"],
            expected["height"], expected["reason"]))


if __name__ == "__main__":
    main()
