"""Deterministic synthetic fixtures for the backup/recovery contract.

Every byte written here is fixed in source so a re-run produces identical
manifest digests. No real guest path, package state or deployment is read.
"""
from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

from canopy_features.backup_recovery import (
    BackupPlan,
    ProvenanceRecord,
    SourceSpec,
    build_plan,
)

CAPTURED_AT = "2026-11-28T00:00:00Z"
DEPLOYMENT = "deployment.20261128.0"
PLAN_ID = "backup_plan_synthetic"

_FIXTURE_FILES = {
    "owner_data/notes.txt": b"synthetic owner note\nline two\n",
    "owner_data/prefs.json": b'{"theme":"synthetic","scale":100}\n',
    "versioned_state/session.json": b'{"shell":"canopy","mode":"classic"}\n',
}


@dataclass(frozen=True)
class SyntheticFixture:
    """Paths and contract records produced by :func:`build_fixture`."""

    root: Path
    source_root: Path
    state_dir: Path
    plan: BackupPlan
    provenance: ProvenanceRecord

    def path_for(self, relative: str) -> Path:
        return self.source_root.joinpath(*relative.split("/"))


def build_fixture(base_dir) -> SyntheticFixture:
    """Create a bounded deterministic fixture tree under ``base_dir``."""
    root = Path(base_dir)
    source_root = root / "source"
    state_dir = root / "state"
    root.mkdir(parents=True, exist_ok=True)
    source_root.mkdir(parents=True, exist_ok=True)
    state_dir.mkdir(parents=True, exist_ok=True)
    for relative, payload in _FIXTURE_FILES.items():
        target = source_root.joinpath(*relative.split("/"))
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(payload)

    plan = build_plan(
        PLAN_ID, DEPLOYMENT,
        [
            SourceSpec("notes", "owner_data/notes.txt", "owner_data"),
            SourceSpec("prefs", "owner_data/prefs.json", "owner_data"),
            SourceSpec("session", "versioned_state/session.json", "versioned_state"),
        ],
        "synthetic fixture for contract checks",
    )
    provenance = ProvenanceRecord(
        PLAN_ID, DEPLOYMENT, "SYNTHETIC", CAPTURED_AT,
        "generated by tools/lacos_backup_recovery",
    )
    return SyntheticFixture(root, source_root, state_dir, plan, provenance)


def tamper_one(fixture: SyntheticFixture, logical_name: str = "notes") -> str:
    """Mutate one synthetic file and return its logical name."""
    mapping = {"notes": "owner_data/notes.txt", "prefs": "owner_data/prefs.json",
               "session": "versioned_state/session.json"}
    relative = mapping[logical_name]
    target = fixture.path_for(relative)
    target.write_bytes(target.read_bytes() + b"tampered\n")
    return logical_name


def write_document(path, document) -> None:
    """Persist a canonical JSON document with LF endings and no timestamps."""
    Path(path).write_bytes(
        (json.dumps(document, sort_keys=True, separators=(",", ":")) + "\n").encode("utf-8"))
